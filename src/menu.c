    void wait_for_enter(void) {
        fd_set input;
        struct timeval timeout;
        int c;

        FD_ZERO(&input);
        FD_SET(STDIN_FILENO, &input);

        timeout.tv_sec=0;
        timeout.tv_usec=0;

        if (select(STDIN_FILENO + 1, &input, NULL, NULL, &timeout) > 0) {
            while ((c = getchar()) != '\n' && c != EOF) {
                // Consume the input until newline or EOF
            }                
        }
        getchar();
        }


    
 
